"""Склейка группы и варианта в одну строку — тексты из файлов врача."""
import pytest

from orthofill.render import join_group


@pytest.mark.parametrize("group, variant, expected", [
    ("Смена дуги на верхней челюсти", 'на верхней челюсти 0.018×0.025" NiTi',
     'Смена дуги на верхней челюсти 0.018×0.025" NiTi.'),
    ("Смена дуги", 'на верхней челюсти 0.018×0.025" TMA',
     'Смена дуги на верхней челюсти 0.018×0.025" TMA.'),
    ("Явка на следующую активацию через", "6 недель.",
     "Явка на следующую активацию через 6 недель."),
    ("Тип системы", "Тип системы: вестибулярная самолигируемая.",
     "Тип системы: вестибулярная самолигируемая."),
    ("Тип системы", "вестибулярная лигатурная.", "Тип системы вестибулярная лигатурная."),
    ("Гигиена:", "Гигиена полости рта удовлетворительная. ",
     "Гигиена полости рта удовлетворительная."),
    ("Соотношение моляров справа:", "Соотношение моляров справа по I классу",
     "Соотношение моляров справа по I классу"),
    ("Назначены межчелюстные эластики", "Перепел", "Назначены межчелюстные эластики: Перепел."),
    ("Юстировка дуги", "Изгиб третьего порядка", "Юстировка дуги: Изгиб третьего порядка."),
    ("Эластическая цепочка без шага", " на нижней челюсти.",
     "Эластическая цепочка без шага на нижней челюсти."),
    ("Динамика лечения", "Динамика лечения соответствует плану.",
     "Динамика лечения соответствует плану."),
    ("Состояние брекет-системы", "удовлетворительное.",
     "Состояние брекет-системы удовлетворительное."),
])
def test_join_group(group, variant, expected):
    assert join_group(group, variant) == expected


def test_variant_equal_to_group():
    assert join_group("Этап", "Этап") == "Этап"
