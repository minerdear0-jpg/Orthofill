def test_wires():
    bad = []
    for raw, exp in WIRE_CASES:
        got = o.parse_wire_from_raw(o.norm(raw))
        if got != exp:
            bad.append(f"  {raw!r}\n    ждали    {exp}\n    получили {got}")
    assert not bad, "\n" + "\n".join(bad)

def test_labels_cyrillic_c():
    # в order.xlsx «СuNiTi» с кириллической С
    assert o.parse_wire_from_label('на верхней челюсти 0.016×0.025" СuNiTi') == \
        (U, ('16', '25'), 'CuNiTi')
    assert o.parse_wire_from_label('на нижней челюсти 0.014" NiTi') == (L, ('14', None), 'NiTi')

def test_reference_xlsx():
    xlsx = Path(__file__).with_name('order.xlsx')
    assert o.run_tests(str(xlsx), o.load_config()) == 0

if __name__ == '__main__':
    fails = 0
    for name, fn in list(globals().items()):
        if name.startswith('test_'):
            try:
                fn()
                print(f"[OK]   {name}")
            except AssertionError as e:
                fails += 1
                print(f"[FAIL] {name}{e}")
    sys.exit(1 if fails else 0)
